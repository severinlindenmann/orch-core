AGENTS_FILE = "AGENTS.orch.md"
SKILLS_DIR = ".agents/skills"  # canonical
CLAUDE_SKILLS_DIR = ".claude/skills"  # a generated copy, or the place older orch versions wrote to
BEGIN = "<!-- orch:begin -->"
END = "<!-- orch:end -->"
AGENTS_BLOCK = f"{BEGIN}\nThis project uses orch for tickets: read AGENTS.orch.md before working on a ticket.\n{END}"
#: the same block for a workspace whose store is ``.orch/`` (the pointer file stays at the root, where others read it)
AGENTS_BLOCK_STORE = (
    f"{BEGIN}\nThis project uses orch for tickets: read .orch/AGENTS.orch.md before working on a ticket.\n{END}"
)
LEGACY_AGENTS_POINTER = "Before working on tickets, read AGENTS.orch.md (orch)."
CLAUDE_IMPORT = "@AGENTS.md"
LEGACY_CLAUDE_IMPORT = "@AGENTS.orch.md"
COPY_HEADER = "<!-- generated by orch from .agents/skills \u2014 do not edit -->"


def _with_header(text: str) -> str:
    """``SKILL.md`` for the generated Claude copy: the header comment goes right after the frontmatter."""
    lines = text.split("\n")
    end = lines.index("---", 1)
    return "\n".join([*lines[: end + 1], COPY_HEADER, *lines[end + 1 :]])


def workspace_files(extra: tuple[str, ...] = ()) -> dict[str, str]:
    """``{path relative to the workspace: content}`` of the files orch owns and rewrites on ``instructions sync``:
    ``AGENTS.orch.md``, the skills in ``.agents/skills`` and the generated copy in ``.claude/skills``."""
    files = {AGENTS_FILE: render_agents_md(extra)}
    for skill in builtin_skills():
        for rel, text in skill.files().items():
            files[f"{SKILLS_DIR}/{rel}"] = text
    for skill in builtin_skills():
        for rel, text in skill.files().items():
            files[f"{CLAUDE_SKILLS_DIR}/{rel}"] = _with_header(text) if rel.endswith("/SKILL.md") else text
    return files


def plugin_files() -> dict[str, str]:
    """The plugin layout below ``packages/core/``: the skills and the hooks."""
    files = {f"skills/{rel}": text for skill in builtin_skills() for rel, text in skill.files().items()}
    hooks = {
        "hooks": {
            "SessionStart": [
                {
                    "matcher": "startup|resume|clear|compact",
                    "hooks": [{"type": "command", "command": "orch instructions hook session-start"}],
                }
            ],
            "PreCompact": [{"hooks": [{"type": "command", "command": "orch instructions hook pre-compact"}]}],
            "Notification": [
                {
                    "matcher": "idle_prompt|permission_prompt",
                    "hooks": [{"type": "command", "command": "orch instructions hook waiting"}],
                }
            ],
        }
    }
    files["hooks/hooks.json"] = json.dumps(hooks, indent=2) + "\n"
    return files


READ_LIMIT = 1 << 20


class UnsafePath(OSError):
    """A path orch would write or read is, or lies below, a symbolic link (or is not a regular file)."""


def _check_chain(root: Path, rel: str) -> Path:
    """``root / rel`` after checking, with ``lstat``, that no component below ``root`` is a symbolic link and that every
    component that exists is a directory (the last one may be a regular file or missing)."""
    cur = root
    parts = Path(rel).parts
    for i, part in enumerate(parts):
        cur = cur / part
        try:
            st = os.lstat(cur)
        except FileNotFoundError:
            continue
        if stat.S_ISLNK(st.st_mode):
            raise UnsafePath(f"{rel}: {part} is a symbolic link; orch does not write through links")
        last = i == len(parts) - 1
        if (not last and not stat.S_ISDIR(st.st_mode)) or (
            last and not (stat.S_ISREG(st.st_mode) or stat.S_ISDIR(st.st_mode))
        ):
            raise UnsafePath(f"{rel}: {part} is not a regular file or directory")
    return cur


def safe_read(root: Path, rel: str) -> str | None:
    """The text of ``root / rel``, or ``None`` if there is no such file. Never follows a link (``UnsafePath``)."""
    path = _check_chain(root, rel)
    from orch.store.fsio import open_regular

    try:  # O_NOFOLLOW | O_NONBLOCK, a regular file only (a FIFO swapped in after the check never blocks, #564)
        fd = open_regular(path, os.O_RDONLY)
    except FileNotFoundError:
        return None
    except OSError as e:  # ELOOP: it became a link between the check and the open; or not a regular file now
        raise UnsafePath(f"{rel}: {e.strerror or 'not a regular file'}") from None
    with os.fdopen(fd, "rb") as f:
        st = os.fstat(f.fileno())
        if not stat.S_ISREG(st.st_mode):
            raise UnsafePath(f"{rel}: not a regular file")
        if st.st_size > READ_LIMIT:
            raise UnsafePath(f"{rel}: larger than {READ_LIMIT >> 20} MiB, orch will not rewrite it")
        return f.read(READ_LIMIT + 1).decode("utf-8")


def _write(root: Path, rel: str, text: str) -> bool:
    """Write ``text`` (LF, UTF-8) to ``root / rel`` unless it is already there; True if the file changed. No component
    is followed if it is a link; the temporary file is made with ``mkstemp`` (exclusive, random name) beside the
    target."""
    path = _check_chain(root, rel)
    try:
        if safe_read(root, rel) == text:
            return False
    except UnicodeDecodeError:
        pass
    parent = path.parent
    rel_parent = Path(rel).parent
    cur = root
    for part in rel_parent.parts:  # make the missing directories one by one, each checked after it exists
        cur = cur / part
        if not cur.exists():
            cur.mkdir()
        _check_chain(root, str(cur.relative_to(root)))
    fd, tmp_name = tempfile.mkstemp(prefix=".orch-", suffix=".tmp", dir=parent)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(text.encode("utf-8"))
        with contextlib.suppress(OSError):
            os.chmod(tmp_name, 0o644)
        _check_chain(root, rel)  # still no link on the way
        os.replace(tmp_name, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp_name)
        raise
    return True


def _ensure_line(root: Path, rel: str, line: str) -> bool:
    """Append ``line`` to ``root / rel`` (created if missing) unless a line equal to it is there. True if changed."""
    have = safe_read(root, rel) or ""
    if line in have.split("\n"):
        return False
    sep = "" if not have or have.endswith("\n") else "\n"
    return _write(root, rel, have + sep + line + "\n")


def _claude_is_agents_link(root: Path) -> bool:
    """True if ``CLAUDE.md`` is a symbolic link to ``AGENTS.md`` (a common setup): the block in ``AGENTS.md`` then
    covers it, and orch leaves ``CLAUDE.md`` alone instead of refusing."""
    claude, agents = root / "CLAUDE.md", root / "AGENTS.md"
    try:
        if not stat.S_ISLNK(os.lstat(claude).st_mode) or stat.S_ISLNK(os.lstat(agents).st_mode):
            return False
        return os.path.realpath(claude) == os.path.realpath(agents) and Path(os.path.realpath(agents)).parent == (
            Path(os.path.realpath(root))
        )
    except OSError:
        return False


def _where(root: Path, store: Path | None, rel: str) -> str:
    """``rel`` as a path below the project ``root``: ``AGENTS.orch.md`` lives in the store (``.orch/AGENTS.orch.md``),
    everything else at its own place. Every check and write goes through ``root`` and this path, so the link check
    covers the ``.orch`` component too."""
    if store is None or rel != AGENTS_FILE or store == root:
        return rel
    return f"{store.relative_to(root).as_posix()}/{rel}"


def agents_rel(root: Path, store: Path | None) -> str:
    """Where ``AGENTS.orch.md`` is, relative to the project ``root``."""
    return _where(root, store, AGENTS_FILE)


def check_targets(root: Path, store: Path | None = None) -> list[str]:
    """Why the instruction files cannot be written safely into ``root`` and ``store`` (the directory that holds
    ``AGENTS.orch.md``; ``None``: ``root``) (empty when they can)."""
    problems = []
    rels = [AGENTS_FILE, "AGENTS.md", "CLAUDE.md", ".gitignore", *workspace_files()]
    link = _claude_is_agents_link(root)
    for rel in dict.fromkeys(rels):
        if rel == "CLAUDE.md" and link:
            continue
        try:
            _check_chain(root, _where(root, store, rel))
        except UnsafePath as e:
            problems.append(str(e))
    return problems


def _agents_md_text(have: str, create: bool, moved: bool = False) -> str | None:
    """``AGENTS.md`` with the orch block: replaced in place, or the old one-line pointer turned into it, or (with
    ``create``) appended. ``None`` if nothing is to be done. Unbalanced markers: :class:`UnsafePath` (fail closed)."""
    lines = have.split("\n")
    begins = [i for i, x in enumerate(lines) if x.strip() == BEGIN]
    ends = [i for i, x in enumerate(lines) if x.strip() == END]
    text_block = AGENTS_BLOCK_STORE if moved else AGENTS_BLOCK
    block = text_block.split("\n")
    if begins or ends:
        if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
            raise UnsafePath("AGENTS.md: the orch:begin / orch:end markers are not one matching pair; fix them by hand")
        out = [*lines[: begins[0]], *block, *lines[ends[0] + 1 :]]
    elif LEGACY_AGENTS_POINTER in lines:
        i = lines.index(LEGACY_AGENTS_POINTER)
        out = [*lines[:i], *block, *(x for x in lines[i + 1 :] if x != LEGACY_AGENTS_POINTER)]
    elif create:
        if not have:
            return text_block + "\n"
        return have + ("" if have.endswith("\n") else "\n") + "\n" + text_block + "\n"
    else:
        return None
    text = "\n".join(out)
    return None if text == have else text


def _claude_md_text(have: str, create: bool, moved: bool = False) -> str | None:
    """``CLAUDE.md`` with the import lines. Legacy layout: ``@AGENTS.md`` (the project rules) then ``@AGENTS.orch.md``;
    missing lines are added when ``create`` (``init``) or when the orch line is already there (``sync`` completing an
    older file: ``@AGENTS.md`` goes right before it). ``moved`` (the store is ``.orch/``): only ``@AGENTS.md`` (whose
    orch block points to ``.orch/AGENTS.orch.md``); orch's own old ``@AGENTS.orch.md`` line is dropped, as it would
    import a file that is no longer there. Other lines are never touched. ``None`` if nothing is to be done."""
    lines = have.split("\n")
    if moved:
        if LEGACY_CLAUDE_IMPORT not in lines and not (create and CLAUDE_IMPORT not in lines):
            return None
        out = [x for x in lines if x != LEGACY_CLAUDE_IMPORT]
        text = "\n".join(out)
        if CLAUDE_IMPORT not in out:
            if LEGACY_CLAUDE_IMPORT in lines:
                i = lines.index(LEGACY_CLAUDE_IMPORT)
                text = "\n".join([*lines[:i], CLAUDE_IMPORT, *[x for x in lines[i + 1 :] if x != LEGACY_CLAUDE_IMPORT]])
            else:
                text += ("" if not text or text.endswith("\n") else "\n") + CLAUDE_IMPORT + "\n"
        return None if text == have else text
    if not create and LEGACY_CLAUDE_IMPORT not in lines:
        return None
    text = have
    if CLAUDE_IMPORT not in lines:
        if LEGACY_CLAUDE_IMPORT in lines:
            i = lines.index(LEGACY_CLAUDE_IMPORT)
            text = "\n".join([*lines[:i], CLAUDE_IMPORT, *lines[i:]])
        else:
            text += ("" if not text or text.endswith("\n") else "\n") + CLAUDE_IMPORT + "\n"
    if LEGACY_CLAUDE_IMPORT not in text.split("\n"):
        text += ("" if not text or text.endswith("\n") else "\n") + LEGACY_CLAUDE_IMPORT + "\n"
    return None if text == have else text


def _read_pointer_file(root: Path, rel: str) -> str:
    """The text of ``AGENTS.md`` / ``CLAUDE.md`` / ``.gitignore`` (empty if missing); anything unsafe to rewrite
    (link, FIFO, over 1 MiB, not UTF-8) is :class:`UnsafePath`."""
    try:
        return safe_read(root, rel) or ""
    except UnicodeDecodeError:
        raise UnsafePath(f"{rel}: not valid UTF-8, orch will not rewrite it") from None


def write_workspace_files(
    root: Path,
    *,
    pointers: bool = True,
    owned: Mapping[str, str] | None = None,
    force: bool = False,
    dry_run: bool = False,
    store: Path | None = None,
) -> tuple[list[str], list[str]]:
    """Write the instruction files into ``root``. Returns ``(changed, kept)``: the relative paths that changed (or
    would, with ``dry_run``) and a line for each file left alone and why.

    ``pointers`` also creates the ``AGENTS.md`` block and the ``CLAUDE.md`` imports (``orch setup`` does); without it
    (``instructions sync``) an existing block, old pointer or old import is still brought up to date, nothing else is
    added. ``AGENTS.md`` and ``CLAUDE.md`` are read and checked first: an unsafe one fails before anything is written,
    except a ``CLAUDE.md`` that links to ``AGENTS.md``, which is skipped with a note. The skills are written to
    ``.agents/skills`` and, as a generated copy, to ``.claude/skills`` (never deleted). A skill whose sidecar names
    another scope than ``builtin`` is the owner's and is kept; so is one without a sidecar unless its ``SKILL.md`` is
    the shipped text, and a ``SKILL.md`` that differs from the shipped text at the same ``skill_version`` (edited by
    hand) unless ``force``. Nothing is written through a symbolic link: :class:`UnsafePath`. ``store``: the store
    directory (``.orch``); ``AGENTS.orch.md`` is written there, everything else under ``root``."""
    if not dry_run and store is not None and store != root:  # the store folder is never made here
        try:
            mode = os.lstat(store).st_mode
        except OSError:
            raise UnsafePath(f"there is no store folder at {store}; nothing was written") from None
        if stat.S_ISLNK(mode):
            raise UnsafePath(f"{store} is a symbolic link; nothing was written")
        if not stat.S_ISDIR(mode):
            raise UnsafePath(f"{store} is not a store folder; nothing was written")
    changed: list[str] = []
    kept: list[str] = []
    skip_dirs: set[str] = set()
    checked: set[str] = set()
    files = dict(owned) if owned is not None else workspace_files()
    moved = store is not None and store != root  # the store is <root>/.orch: the pointers and the ignore line follow it
    # the pointer files first: any problem is found before anything is written
    agents_have = _read_pointer_file(root, "AGENTS.md")
    if _claude_is_agents_link(root):
        claude_new = None
        kept.append("kept CLAUDE.md (a link to AGENTS.md; the orch block there covers it)")
    else:
        claude_new = _claude_md_text(_read_pointer_file(root, "CLAUDE.md"), pointers, moved)
    agents_new = _agents_md_text(agents_have, pointers or claude_new is not None, moved)
    gitignore_have = _read_pointer_file(root, ".gitignore") if pointers else ""
    ignore_line = ".orch/" if moved else ".state/"
    for rel, text in files.items():
        skill_dir = _skill_dir(rel)
        if skill_dir is not None:
            if skill_dir not in checked:
                checked.add(skill_dir)
                shipped = files.get(skill_dir + "/SKILL.md", "")
                reason = _keep_reason(root, skill_dir, force, (shipped, _plain(shipped)) if shipped else ())
                if reason:
                    skip_dirs.add(skill_dir)
                    kept.append(f"kept {skill_dir} ({reason})")
            if skill_dir in skip_dirs:
                continue
        where = _where(root, store, rel)
        if dry_run:
            if safe_read(root, where) != text:
                changed.append(where)
        elif _write(root, where, text):
            changed.append(where)
    for rel, new in (("AGENTS.md", agents_new), ("CLAUDE.md", claude_new)):
        if new is not None:
            _check_chain(root, rel)
            if dry_run or _write(root, rel, new):
                changed.append(rel)
    if pointers and ignore_line not in gitignore_have.split("\n"):
        if dry_run or _ensure_line(root, ".gitignore", ignore_line):
            changed.append(".gitignore")
    return changed, kept


def _skill_dir(rel: str) -> str | None:
    """``.agents/skills/x`` for ``.agents/skills/x/SKILL.md`` (also below ``.claude/skills``), else ``None``."""
    for base in (SKILLS_DIR, CLAUDE_SKILLS_DIR):
        if rel.startswith(base + "/") and rel.count("/") == base.count("/") + 2:
            return rel.rsplit("/", 1)[0]
    return None


def _plain(headed: str) -> str:
    """The ``SKILL.md`` text without the copy header (what older orch versions wrote to ``.claude/skills``)."""
    return headed.replace(COPY_HEADER + "\n", "", 1)


def _keep_reason(root: Path, skill_dir: str, force: bool, accepted: tuple[str, ...]) -> str | None:
    """Why the skill in ``skill_dir`` must not be overwritten, or ``None``. ``accepted`` are the ``SKILL.md`` texts
    that count as unedited at the shipped ``skill_version``."""
    side = None
    try:
        side = safe_read(root, skill_dir + "/orch.skill.json")
        have = json.loads(side) if side is not None else None
    except (ValueError, UnicodeDecodeError):
        have = None
    if side is None:  # no sidecar: orch's only if the SKILL.md is exactly what orch ships
        try:
            current = safe_read(root, skill_dir + "/SKILL.md")
        except UnicodeDecodeError:
            current = ""
        if current is not None and current not in accepted:
            return "no sidecar, not orch's"
        return None
    if not isinstance(have, dict):
        return None
    if have.get("scope") not in (None, "builtin"):
        return f"scope {have['scope']}, not orch's"
    if force:
        return None
    name = skill_dir.rsplit("/", 1)[1]
    skill = next((k for k in builtin_skills() if k.name == name), None)
    if skill is not None and have.get("skill_version") == skill.version and accepted:
        try:
            current = safe_read(root, skill_dir + "/SKILL.md")
        except UnicodeDecodeError:
            current = None
        if current is not None and current not in accepted:
            return "edited by hand; --force overwrites it, or set scope workspace in orch.skill.json to keep it"
    return None
