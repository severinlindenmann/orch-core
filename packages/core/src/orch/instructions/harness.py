"""Which files the instructions become, per harness (harnesses §2).

* **Every harness:** ``AGENTS.orch.md`` in the workspace directory, and the built-in skills as ``SKILL.md`` folders in
  the provider-neutral ``.agents/skills/<name>/`` (the canonical copy).
* **Codex and other readers of ``AGENTS.md``:** one marked block (``<!-- orch:begin -->`` ... ``<!-- orch:end -->``) in
  ``AGENTS.md`` that points to ``AGENTS.orch.md``: created or appended if there is none, replaced in place otherwise;
  an old one-line pointer becomes the block; nothing else in the file is touched.
* **Claude Code:** ``CLAUDE.md`` holds the two import lines ``@AGENTS.md`` (the project rules) and ``@AGENTS.orch.md``;
  a generated copy of the skills in ``.claude/skills`` that carries the header :data:`COPY_HEADER` (always written,
  never deleted: next to the plugin's skills it is a harmless duplicate); and the plugin layout of
  ``packages/core/`` (``skills/`` and ``hooks/hooks.json``), generated by :func:`plugin_files` and kept equal to
  the repository by a test. The plugin's hooks run ``orch instructions hook session-start`` and ``pre-compact``.

The guard hook (tier C) is not part of this module.
"""

