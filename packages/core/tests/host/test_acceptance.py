def criterion(human):
    uid, key = human.ticket()
    human.run("ac.add", {"ref": key, "text": "It works"})
    return uid, key


@pytest.mark.parametrize("text", ["one", "one\ntwo", "one\n", "| note:\nreason:"])
@pytest.mark.parametrize("note", [None, "checked", "first\nsecond\n"])
def test_statement_round_trip(text, note):
    statement = acceptance.build_accept("AC2", text, note)
    assert acceptance.parse(statement) == {
        "kind": "accept",
        "ac": "AC2",
        "hash": criterion_hash("AC2", text),
        "text": text,
        "note": note,
    }
    withdrawn = acceptance.build_withdraw("AC2", text, "changed\nmy mind")
    assert acceptance.parse(withdrawn)["reason"] == "changed\nmy mind"
    assert statement.endswith("\n") and not statement.endswith("\n\n")


def test_every_byte_mutation_of_a_statement_without_note_is_refused():
    raw = acceptance.build_accept("AC2", "It works").encode()
    # Replacing any byte with a different ASCII byte cannot repair its hash or its grammar.
    for index, before in enumerate(raw):
        for replacement in range(128):
            if replacement != before:
                changed = raw[:index] + bytes([replacement]) + raw[index + 1 :]
                assert acceptance.parse(changed.decode()) is None, (index, replacement)
    for index in range(len(raw)):
        assert acceptance.parse((raw[:index] + raw[index + 1 :]).decode()) is None


@pytest.mark.parametrize("note", ["", "x" * 1001, "bad\x00", "bad\t", "bad\x7f", "bad\u202e"])
def test_bad_notes_refused(note):
    with pytest.raises(ValueError):
        acceptance.build_accept("AC1", "criterion", note)
    with pytest.raises(ValueError):
        acceptance.build_withdraw("AC1", "criterion", note)


def test_normalization_is_only_at_build_time():
    statement = acceptance.build_accept("AC1", "criterion", "e\u0301\r\nchecked")
    assert acceptance.parse(statement)["note"] == "é\nchecked"
    assert acceptance.parse(statement.replace("é", "e\u0301")) is None
    assert acceptance.parse(statement.replace("\n", "\r\n")) is None
    assert acceptance.parse(statement + "\n") is None
    assert (
        acceptance.parse(acceptance.build_withdraw("AC1", "criterion", "why").replace("reason:\n| why\n", "")) is None
    )


def test_accept_withdraw_and_read_states(human, served):
    uid, key = criterion(human)
    prepared, _, signed = human.run("ac.accept", {"ref": key, "ac": "AC1", "note": "I checked"})
    event = signed.events[0]
    assert event["label"] == label("AC1", "It works")
    assert event["name"] == "accept-AC1-1.md"
    statement = prepared["material"]["statement"]
    assert event["sha256"] == canon.artifact_digest(statement.encode())
    assert prepared["material"]["review"][0]["derived"] == {"statement": statement}
    signer.check_uploads(prepared, None)  # generated bytes, independently rebuilt
    plain = signcontent.build(prepared, verified=True)
    assert "Accept AC1" in plain["headline"]
    assert "No automated check backs this: you vouch for it yourself." in plain["notes"]
    assert "| orch manual acceptance v1" in signer.render(prepared, lambda _: ("demo", "DEMO"))
    data = ok(human.c.req("ticket.get", {"ref": key}))["data"]
    ac = data["criteria"][0]
    assert ac["proof"] == "accepted" and ac["covered"]
    assert ac["accepted"] == {
        "by": human.person.ref,
        "at": data["artifacts"][0]["at"],
        "auth": "passphrase",
        "note": "I checked",
        "statement_ok": True,
    }
    assert err(human.prepare_res("ac.accept", {"ref": key, "ac": "AC1"})) == "invalid.input"
    old_gen = data["gates"]["verify"]["gen"]
    human.run("ac.edit", {"ref": key, "ac": "AC1", "text": "New wording"})
    data = ok(human.c.req("ticket.get", {"ref": key}))["data"]
    assert data["criteria"][0]["accepted_stale"] and not data["criteria"][0]["covered"]
    assert "accepted" not in data["criteria"][0]
    _, _, signed = human.run("ac.unaccept", {"ref": key, "ac": "AC1", "reason": "recheck"})
    assert "ac" not in signed.events[0] and signed.events[0]["name"] == event["name"]
    assert signed.events[0]["replaces"] == event["sha256"]
    data = ok(human.c.req("ticket.get", {"ref": key}))["data"]
    assert not data["criteria"][0]["covered"] and data["gates"]["verify"]["gen"] > old_gen
    assert err(human.prepare_res("ac.unaccept", {"ref": key, "ac": "AC1", "reason": "again"})) == "not_found"
    prepared, _, _ = human.run("ac.accept", {"ref": key, "ac": "AC1"})
    assert prepared["events"][0]["name"] == "accept-AC1-2.md"


@pytest.mark.parametrize("mutation", ["statement", "sha", "missing_ac", "label", "extra", "name", "bytes", "type"])
def test_signer_rejects_even_when_host_recomputes_review(human, mutation):
    _, key = criterion(human)
    prepared = human.prepare("ac.accept", {"ref": key, "ac": "AC1", "note": "checked"})
    p = copy.deepcopy(prepared)
    e = p["events"][0]
    if mutation == "statement":
        p["material"]["statement"] = p["material"]["statement"].replace("checked", "changed")
    elif mutation == "sha":
        e["sha256"] = "sha256:" + "0" * 64
    elif mutation == "missing_ac":
        del e["ac"]
    elif mutation == "label":
        e["label"] = label("AC1", "different wording")
    elif mutation == "extra":
        e["task"] = "T1"
    elif mutation == "name":
        e["name"] = "accept-AC2-1.md"
    elif mutation == "bytes":
        e["bytes"] += 1
    else:
        e["type"] = "artifact.replaced"
    with pytest.raises(review.ReviewError):  # an honest host cannot even build the review of a mismatch
        review.of(e, p["material"])
    # a dishonest host builds it by hand: the signer still rebuilds and refuses
    p["material"]["review"] = [
        {
            "event_id": e["id"],
            "type": e["type"],
            "payload": review.payload(e),
            "derived": {"statement": p["material"]["statement"]},
        }
    ]
    p["review_digest"] = review.review_digest(p["material"])
    p["fingerprint"] = review.fingerprint(p["review_digest"], p["events"], p["op"])
    with pytest.raises(signer.SignerRefused):
        human.check(p)
    with pytest.raises(signer.SignerRefused):
        signer.verify_material(p, workspace_id=p["workspace_id"])


def test_plain_and_granted_requests_are_human_only(human, served):
    _, key = criterion(human)
    for op, args in (
        ("ac.accept", {"ref": key, "ac": "AC1"}),
        ("ac.unaccept", {"ref": key, "ac": "AC1", "reason": "why"}),
        ("task.mark_done", {"ref": key, "task": "T1"}),
    ):
        assert err(human.c.req(op, args, idem=True)) == "human_only"
        assert err(human.c.req(op, args, grant=served.grant, session=SESSION, idem=True)) == "human_only"
        assert err(human.prepare_res(op, args, grant=served.grant, session=SESSION)) == "human_only"


@pytest.mark.parametrize("role", ["member", "viewer"])
def test_plain_member_and_viewer_cannot_accept(tmp_path, role):
    w = world(tmp_path, map_to="quinn")
    try:
        uid, key = w.ticket()
        if role == "viewer":
            w.person_event("role.changed", person=w.quinn.ref, role="viewer")
        quinn = Human(w, w.quinn)
        # Authority is checked before AC lookup, including for a viewer who reviews the ticket.
        assert err(quinn.prepare_res("ac.accept", {"ref": key, "ac": "AC1"})) == "role.denied"
        assert err(quinn.prepare_res("task.mark_done", {"ref": key, "task": "T1"})) == "role.denied"
    finally:
        w.close()
        w.lab.close()


def test_mark_done_is_person_without_receipt_or_ac_evidence(human):
    _, key = criterion(human)
