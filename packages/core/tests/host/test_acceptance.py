def test_reader_rejects_noncanonical_or_mismatched_files():
    from types import SimpleNamespace

    raw = acceptance.build_accept("AC1", "It works").encode()
    art = SimpleNamespace(
        kind="feedback",
        by="p_" + "1" * 32,
        evidence_ok=True,
        ac="AC1",
        label=label("AC1", "It works"),
        digest=canon.artifact_digest(raw),
        bytes=len(raw),
    )
    assert acceptance.artifact_statement(art, raw) is not None
    assert acceptance.artifact_statement(art, raw + b"x") is None
    bad = b"not a statement\n"
    art.digest, art.bytes = canon.artifact_digest(bad), len(bad)
    assert acceptance.artifact_statement(art, bad) is None
    art.digest, art.bytes = canon.artifact_digest(raw), len(raw)
    art.label = label("AC1", "other text")
    assert acceptance.artifact_statement(art, raw) is None
    art.label, art.kind, art.by = label("AC1", "It works"), "other", "s_agent"
    assert acceptance.artifact_statement(art, raw) is None


def test_a_statement_is_shown_only_when_it_is_the_one_the_event_signs(human):
    _, key = criterion(human)
    prepared = human.prepare("ac.accept", {"ref": key, "ac": "AC1", "note": "checked"})
    event, material = prepared["events"][0], copy.deepcopy(prepared["material"])
    assert review.derived(event, material) == {"statement": material["statement"]}
    material["statement"] = material["statement"].replace("checked", "changed")
    with pytest.raises(review.ReviewError):
        review.derived(event, material)
    material["statement"] = 5
    with pytest.raises(review.ReviewError):
        review.derived(event, material)


