@pytest.mark.parametrize("authority", ["reviewer", "owner", "maintainer"])
def test_member_with_ticket_authority_or_maintainer_can_accept(tmp_path, authority):
    w = world(tmp_path, map_to="quinn")
    try:
        uid, key = w.ticket()
        quinn = Human(w, w.quinn)
        quinn.run("ac.add", {"ref": key, "text": "It works"})
        if authority == "maintainer":
            w.person_event("role.changed", person=w.quinn.ref, role="maintainer")
        else:
            w.person_event(
                "people.changed",
                uid,
                role="reviewers" if authority == "reviewer" else "owner",
                add=[w.quinn.ref],
                remove=[],
            )
        quinn.run("ac.accept", {"ref": key, "ac": "AC1"})
        quinn.run("ac.unaccept", {"ref": key, "ac": "AC1", "reason": "recheck"})
        w.person_event("role.changed", person=w.quinn.ref, role="viewer")
        assert err(quinn.prepare_res("ac.accept", {"ref": key, "ac": "AC1"})) == "role.denied"
    finally:
        w.close()
        w.lab.close()


def test_agent_file_with_acceptance_name_stays_asserted(human):
    import base64

    _, key = criterion(human)
    human.agent("claim", {"ref": key})
    content = acceptance.build_accept("AC1", "It works").encode()
    ok(
        human.c.req(
            "artifact.add",
            {
                "ref": key,
                "path": "upload",
                "name": "accept-AC1.md",
                "kind": "other",
                "ac": "AC1",
                "label": label("AC1", "It works"),
            },
            files={"path": {"b64": base64.b64encode(content).decode()}},
            grant=human.served.grant,
            session=SESSION,
            idem=True,
        )
    )
    ac = ok(human.c.req("ticket.get", {"ref": key}))["data"]["criteria"][0]
    assert ac["proof"] == "asserted" and ac["covered"]
    assert "accepted" not in ac and "accepted_stale" not in ac


def test_plain_view_requires_statement_and_withdraw_signer_rejects_ac(human):
    _, key = criterion(human)
    human.run("ac.accept", {"ref": key, "ac": "AC1"})
    p = human.prepare("ac.unaccept", {"ref": key, "ac": "AC1", "reason": "recheck"})
    human.check(p)
    assert "Withdraw the acceptance of AC1" in signcontent.build(p, verified=True)["headline"]
    missing = copy.deepcopy(p)
    del missing["material"]["statement"]
    with pytest.raises(signcontent.PlainUnavailable):
        signcontent.build(missing, verified=True)
    p["events"][0]["ac"] = "AC1"
    with pytest.raises(signer.SignerRefused):
        signer.check_uploads(p, None)


