"""Which files the instructions become, per harness (harnesses §2).

* **Every harness:** ``AGENTS.orch.md`` in the workspace directory, and the built-in skills as ``SKILL.md`` folders in
  the provider-neutral ``.agents/skills/<name>/`` (the canonical copy).
* **Codex and other readers of ``AGENTS.md``:** one marked block (``<!-- orch:begin -->`` ... ``<!-- orch:end -->``) in
  ``AGENTS.md`` that points to ``AGENTS.orch.md``: created or appended if there is none, replaced in place otherwise;
  an old one-line pointer becomes the block; nothing else in the file is touched.
* **Claude Code:** ``CLAUDE.md`` holds one ``@AGENTS.md`` import line (an old orch-written ``@AGENTS.orch.md`` line is
  replaced by it); the plugin layout of ``plugins/orch-core/`` (``skills/`` and ``hooks/hooks.json``), generated by
  :func:`plugin_files` and kept equal to the repository by a test; and, only when the orch plugin is not enabled for
  the project (:func:`claude_plugin_enabled`), a generated copy of the skills in ``.claude/skills`` that carries the
  header :data:`COPY_HEADER`. The plugin's hooks run ``orch instructions hook session-start`` and ``pre-compact``.

The guard hook (tier C) is not part of this module.
"""

from __future__ import annotations

import contextlib
import json
import os
import stat
import tempfile
from collections.abc import Mapping
from pathlib import Path

from .agents_md import render_agents_md
from .skills import builtin_skills

__all__ = [
    "AGENTS_FILE",
    "AGENTS_BLOCK",
    "CLAUDE_IMPORT",
    "COPY_HEADER",
    "SKILLS_DIR",
    "CLAUDE_SKILLS_DIR",
    "UnsafePath",
    "check_targets",
    "claude_plugin_enabled",
    "safe_read",
    "plugin_files",
    "workspace_files",
    "write_workspace_files",
]

AGENTS_FILE = "AGENTS.orch.md"
SKILLS_DIR = ".agents/skills"  # canonical
CLAUDE_SKILLS_DIR = ".claude/skills"  # a generated copy, or the place older orch versions wrote to
BEGIN = "<!-- orch:begin -->"
END = "<!-- orch:end -->"
AGENTS_BLOCK = f"{BEGIN}\nThis project uses orch for tickets: read AGENTS.orch.md before working on a ticket.\n{END}"
LEGACY_AGENTS_POINTER = "Before working on tickets, read AGENTS.orch.md (orch)."
CLAUDE_IMPORT = "@AGENTS.md"
LEGACY_CLAUDE_IMPORT = "@AGENTS.orch.md"
COPY_HEADER = "<!-- generated by orch from .agents/skills \u2014 do not edit -->"


def claude_plugin_enabled(root: Path) -> bool:
    """True if the project's Claude Code settings (``.claude/settings.json`` or ``settings.local.json``) enable a plugin
    named ``orch-core``. Anything unreadable counts as not enabled (the generated copy is then written, which is
    harmless: it is the same text)."""
    for name in ("settings.json", "settings.local.json"):
        try:
            doc = json.loads(safe_read(root, f".claude/{name}") or "{}")
        except (OSError, ValueError, UnicodeDecodeError):
            continue
        plugins = doc.get("enabledPlugins") if isinstance(doc, dict) else None
        if isinstance(plugins, dict) and any(
            isinstance(k, str) and k.split("@", 1)[0] == "orch-core" and v is True for k, v in plugins.items()
        ):
            return True
    return False


def _with_header(text: str) -> str:
    """``SKILL.md`` for the generated Claude copy: the header comment goes right after the frontmatter."""
    lines = text.split("\n")
    end = lines.index("---", 1)
    return "\n".join([*lines[: end + 1], COPY_HEADER, *lines[end + 1 :]])


def workspace_files(extra: tuple[str, ...] = (), *, claude_copy: bool = True) -> dict[str, str]:
    """``{path relative to the workspace: content}`` of the files orch owns and rewrites on ``instructions sync``:
    ``AGENTS.orch.md``, the skills in ``.agents/skills`` and, with ``claude_copy``, the generated copy in
    ``.claude/skills``."""
    files = {AGENTS_FILE: render_agents_md(extra)}
    for skill in builtin_skills():
        for rel, text in skill.files().items():
            files[f"{SKILLS_DIR}/{rel}"] = text
    if claude_copy:
        for skill in builtin_skills():
            for rel, text in skill.files().items():
                files[f"{CLAUDE_SKILLS_DIR}/{rel}"] = _with_header(text) if rel.endswith("/SKILL.md") else text
    return files


def plugin_files() -> dict[str, str]:
    """The plugin layout below ``plugins/orch-core/``: the skills and the hooks."""
    files = {f"skills/{rel}": text for skill in builtin_skills() for rel, text in skill.files().items()}
    hooks = {
        "hooks": {
            "SessionStart": [
                {
                    "matcher": "startup|resume|clear|compact",
                    "hooks": [{"type": "command", "command": "orch instructions hook session-start"}],
                }
            ],
            "PreCompact": [{"hooks": [{"type": "command", "command": "orch instructions hook pre-compact"}]}],
        }
    }
    files["hooks/hooks.json"] = json.dumps(hooks, indent=2) + "\n"
    return files


READ_LIMIT = 1 << 20


class UnsafePath(OSError):
    """A path orch would write or read is, or lies below, a symbolic link (or is not a regular file)."""


def _check_chain(root: Path, rel: str) -> Path:
    """``root / rel`` after checking, with ``lstat``, that no component below ``root`` is a symbolic link and that every
    component that exists is a directory (the last one may be a regular file or missing)."""
    cur = root
    parts = Path(rel).parts
    for i, part in enumerate(parts):
        cur = cur / part
        try:
            st = os.lstat(cur)
        except FileNotFoundError:
            continue
        if stat.S_ISLNK(st.st_mode):
            raise UnsafePath(f"{rel}: {part} is a symbolic link; orch does not write through links")
        last = i == len(parts) - 1
        if (not last and not stat.S_ISDIR(st.st_mode)) or (
            last and not (stat.S_ISREG(st.st_mode) or stat.S_ISDIR(st.st_mode))
        ):
            raise UnsafePath(f"{rel}: {part} is not a regular file or directory")
    return cur


def safe_read(root: Path, rel: str) -> str | None:
    """The text of ``root / rel``, or ``None`` if there is no such file. Never follows a link (``UnsafePath``)."""
    path = _check_chain(root, rel)
    from orch.store.fsio import open_regular

    try:  # O_NOFOLLOW | O_NONBLOCK, a regular file only (a FIFO swapped in after the check never blocks, #564)
        fd = open_regular(path, os.O_RDONLY)
    except FileNotFoundError:
        return None
    except OSError as e:  # ELOOP: it became a link between the check and the open; or not a regular file now
        raise UnsafePath(f"{rel}: {e.strerror or 'not a regular file'}") from None
    with os.fdopen(fd, "rb") as f:
        st = os.fstat(f.fileno())
        if not stat.S_ISREG(st.st_mode):
            raise UnsafePath(f"{rel}: not a regular file")
        if st.st_size > READ_LIMIT:
            raise UnsafePath(f"{rel}: larger than {READ_LIMIT >> 20} MiB, orch will not rewrite it")
        return f.read(READ_LIMIT + 1).decode("utf-8")


def _write(root: Path, rel: str, text: str) -> bool:
    """Write ``text`` (LF, UTF-8) to ``root / rel`` unless it is already there; True if the file changed. No component
    is followed if it is a link; the temporary file is made with ``mkstemp`` (exclusive, random name) beside the
    target."""
    path = _check_chain(root, rel)
    try:
        if safe_read(root, rel) == text:
            return False
    except UnicodeDecodeError:
        pass
    parent = path.parent
    rel_parent = Path(rel).parent
    cur = root
    for part in rel_parent.parts:  # make the missing directories one by one, each checked after it exists
        cur = cur / part
        if not cur.exists():
            cur.mkdir()
        _check_chain(root, str(cur.relative_to(root)))
    fd, tmp_name = tempfile.mkstemp(prefix=".orch-", suffix=".tmp", dir=parent)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(text.encode("utf-8"))
        with contextlib.suppress(OSError):
            os.chmod(tmp_name, 0o644)
        _check_chain(root, rel)  # still no link on the way
        os.replace(tmp_name, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp_name)
        raise
    return True


def _ensure_line(root: Path, rel: str, line: str) -> bool:
    """Append ``line`` to ``root / rel`` (created if missing) unless a line equal to it is there. True if changed."""
    have = safe_read(root, rel) or ""
    if line in have.split("\n"):
        return False
    sep = "" if not have or have.endswith("\n") else "\n"
    return _write(root, rel, have + sep + line + "\n")


def check_targets(root: Path) -> list[str]:
    """Why the instruction files cannot be written safely into ``root`` (empty when they can)."""
    problems = []
    rels = [AGENTS_FILE, "AGENTS.md", "CLAUDE.md", ".gitignore", *workspace_files()]
    for rel in dict.fromkeys(rels):
        try:
            _check_chain(root, rel)
        except UnsafePath as e:
            problems.append(str(e))
    return problems


def _agents_md_text(have: str, create: bool) -> str | None:
    """``AGENTS.md`` with the orch block: replaced in place, or the old one-line pointer turned into it, or (with
    ``create``) appended. ``None`` if nothing is to be done. Unbalanced markers: ``ValueError`` (fail closed)."""
    lines = have.split("\n")
    begins = [i for i, x in enumerate(lines) if x.strip() == BEGIN]
    ends = [i for i, x in enumerate(lines) if x.strip() == END]
    block = AGENTS_BLOCK.split("\n")
    if begins or ends:
        if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
            raise ValueError("the orch:begin / orch:end markers are not one matching pair")
        out = [*lines[: begins[0]], *block, *lines[ends[0] + 1 :]]
    elif LEGACY_AGENTS_POINTER in lines:
        i = lines.index(LEGACY_AGENTS_POINTER)
        out = [*lines[:i], *block, *(x for x in lines[i + 1 :] if x != LEGACY_AGENTS_POINTER)]
    elif create:
        if not have:
            return AGENTS_BLOCK + "\n"
        return have + ("" if have.endswith("\n") else "\n") + "\n" + AGENTS_BLOCK + "\n"
    else:
        return None
    text = "\n".join(out)
    return None if text == have else text


def _claude_md_text(have: str, create: bool) -> str | None:
    """``CLAUDE.md`` with the ``@AGENTS.md`` import: an old orch-written ``@AGENTS.orch.md`` line is replaced (or
    dropped if the new line is already there); appended if missing and ``create``. Other lines are never touched."""
    lines = have.split("\n")
    if LEGACY_CLAUDE_IMPORT in lines:
        if CLAUDE_IMPORT in lines:
            out = [x for x in lines if x != LEGACY_CLAUDE_IMPORT]
        else:
            out = [CLAUDE_IMPORT if x == LEGACY_CLAUDE_IMPORT else x for x in lines]
        text = "\n".join(out)
    elif CLAUDE_IMPORT in lines or not create:
        return None
    else:
        sep = "" if not have or have.endswith("\n") else "\n"
        text = have + sep + CLAUDE_IMPORT + "\n"
    return None if text == have else text


def write_workspace_files(
    root: Path,
    *,
    pointers: bool = True,
    owned: Mapping[str, str] | None = None,
    force: bool = False,
    dry_run: bool = False,
) -> tuple[list[str], list[str]]:
    """Write the instruction files into ``root``. Returns ``(changed, kept)``: the relative paths that changed (or
    would, with ``dry_run``) and a line for each file left alone and why (also each skill moved out of
    ``.claude/skills``).

    ``pointers`` also creates the ``AGENTS.md`` block and the ``CLAUDE.md`` import (``orch init`` does); without it
    (``instructions sync``) an existing block, old pointer or old import is still brought up to date, nothing else is
    added. The ``.claude/skills`` copy is written unless the orch plugin is enabled for the project; orch-built skills
    found there when it is not wanted move to ``.agents/skills``. A built-in skill whose sidecar names another scope
    than ``builtin`` is the owner's and is kept; so is a ``SKILL.md`` that differs from the shipped text at the same
    ``skill_version`` (edited by hand) unless ``force``. Nothing is written through a symbolic link:
    :class:`UnsafePath`."""
    changed: list[str] = []
    kept: list[str] = []
    skip_dirs: set[str] = set()
    checked: set[str] = set()
    plugin = claude_plugin_enabled(root)
    files = dict(owned) if owned is not None else workspace_files(claude_copy=not plugin)
    for rel, text in files.items():
        skill_dir = _skill_dir(rel)
        if skill_dir is not None:
            if skill_dir not in checked:
                checked.add(skill_dir)
                shipped = files.get(skill_dir + "/SKILL.md", "")
                reason = _keep_reason(root, skill_dir, force, (shipped, _plain(shipped)) if shipped else ())
                if reason:
                    skip_dirs.add(skill_dir)
                    kept.append(f"kept {skill_dir} ({reason})")
            if skill_dir in skip_dirs:
                continue
        if dry_run:
            if safe_read(root, rel) != text:
                changed.append(rel)
        elif _write(root, rel, text):
            changed.append(rel)
    if owned is None and plugin:
        _move_legacy_skills(root, force, dry_run, kept)
    claude_new = _claude_md_text(_read_or_empty(root, "CLAUDE.md"), pointers)
    agents_new = _agents_md_text(_read_or_empty(root, "AGENTS.md"), pointers or claude_new is not None)
    for rel, new in (("AGENTS.md", agents_new), ("CLAUDE.md", claude_new)):
        if new is not None:
            _check_chain(root, rel)
            if dry_run or _write(root, rel, new):
                changed.append(rel)
    if pointers:
        if dry_run:
            if ".state/" not in (safe_read(root, ".gitignore") or "").split("\n"):
                changed.append(".gitignore")
        elif _ensure_line(root, ".gitignore", ".state/"):
            changed.append(".gitignore")
    return changed, kept


def _skill_dir(rel: str) -> str | None:
    """``.agents/skills/x`` for ``.agents/skills/x/SKILL.md`` (also below ``.claude/skills``), else ``None``."""
    for base in (SKILLS_DIR, CLAUDE_SKILLS_DIR):
        if rel.startswith(base + "/") and rel.count("/") == base.count("/") + 2:
            return rel.rsplit("/", 1)[0]
    return None


def _read_or_empty(root: Path, rel: str) -> str:
    return safe_read(root, rel) or ""


def _plain(headed: str) -> str:
    """The ``SKILL.md`` text without the copy header (what older orch versions wrote to ``.claude/skills``)."""
    return headed.replace(COPY_HEADER + "\n", "", 1)


def _move_legacy_skills(root: Path, force: bool, dry_run: bool, kept: list[str]) -> None:
    """The orch plugin supplies the skills: orch-built ones in ``.claude/skills`` (written by an older orch, or by the
    generated copy) are removed, ``.agents/skills`` holds them. Hand-edited and other-scope skills stay."""
    for skill in builtin_skills():
        skill_dir = f"{CLAUDE_SKILLS_DIR}/{skill.name}"
        reason = _keep_reason(root, skill_dir, force, (skill.text, _with_header(skill.text)))
        if reason:
            kept.append(f"kept {skill_dir} ({reason})")
            continue
        try:
            side = safe_read(root, skill_dir + "/orch.skill.json")
            text = safe_read(root, skill_dir + "/SKILL.md")
        except UnicodeDecodeError:
            continue
        if side is None or text is None or text not in (skill.text, _with_header(skill.text)):
            continue  # not (or no longer) the shipped skill: not ours to remove
        kept.append(f"{'would move' if dry_run else 'moved'} {skill_dir} to {SKILLS_DIR}/{skill.name}")
        if dry_run:
            continue
        for name in ("SKILL.md", "orch.skill.json"):
            os.unlink(_check_chain(root, f"{skill_dir}/{name}"))
        with contextlib.suppress(OSError):  # only when empty: other files in it are the owner's
            os.rmdir(_check_chain(root, skill_dir))


def _keep_reason(root: Path, skill_dir: str, force: bool, accepted: tuple[str, ...]) -> str | None:
    """Why the skill in ``skill_dir`` must not be overwritten, or ``None``. ``accepted`` are the ``SKILL.md`` texts
    that count as unedited at the shipped ``skill_version``."""
    try:
        side = safe_read(root, skill_dir + "/orch.skill.json")
        have = json.loads(side) if side is not None else None
    except (ValueError, UnicodeDecodeError):
        have = None
    if not isinstance(have, dict):
        return None
    if have.get("scope") not in (None, "builtin"):
        return f"scope {have['scope']}, not orch's"
    if force:
        return None
    name = skill_dir.rsplit("/", 1)[1]
    skill = next((k for k in builtin_skills() if k.name == name), None)
    if skill is not None and have.get("skill_version") == skill.version and accepted:
        try:
            current = safe_read(root, skill_dir + "/SKILL.md")
        except UnicodeDecodeError:
            current = None
        if current is not None and current not in accepted:
            return "edited by hand; --force overwrites it, or set scope workspace in orch.skill.json to keep it"
    return None
