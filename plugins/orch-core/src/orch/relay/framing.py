def grant_shaped(obj: Any) -> bool:
    """A grant-shaped string anywhere in ``obj`` (keys included)."""
    stack = [obj]
    while stack:
        x = stack.pop()
        if type(x) is str:
            if GRANT_SHAPE.search(x):
                return True
        elif type(x) is list:
            stack.extend(x)
        elif type(x) is dict:
            stack.extend(x.keys())
            stack.extend(x.values())
    return False


@dataclass(frozen=True)
class Request:
    op: str
    spec: OpSpec
    args: dict[str, Any]
    idem: str | None
    rd: str | None


def check_meta(meta: Mapping[str, Any], data: bytes) -> Request:
    """Step 11's first checks, in order, before any column is resolved: ``auth`` -> ``req.invalid``; a grant-shaped
    string -> ``grant.secret_in_args``; an op outside :data:`OPS` -> ``forbidden_scope``; other unknown keys, non-object
    args or non-empty data -> ``req.invalid``; the idem rules (``idem.required`` / ``req.invalid`` /
    ``idem.invalid``)."""
    if "auth" in meta:
        raise Refusal("req.invalid")
    if grant_shaped(meta):
        raise Refusal("grant.secret_in_args")
    spec = OPS.get(meta["op"])
    if spec is None:
        raise Refusal("forbidden_scope")
    if set(meta) - META_KEYS or "args" not in meta or type(meta["args"]) is not dict or data:
        raise Refusal("req.invalid")
    idem = meta.get("idem")
    if spec.kind == "write":
        if idem is None:
            raise Refusal("idem.required")
        if type(idem) is not str or not IDEM_RE.fullmatch(idem):
            raise Refusal("idem.invalid")
    elif "idem" in meta:
        raise Refusal("req.invalid")
    rd = meta.get("rd")
    if "rd" in meta and (type(rd) is not str or not _RD.fullmatch(rd)):
        raise Refusal("req.invalid")
    return Request(meta["op"], spec, dict(meta["args"]), idem, rd)


def refusal_plaintext(code: str, **fields: Any) -> bytes:
    """The plaintext of a refusal chunk: :func:`refusal_meta` (the closed field sets), ``data`` empty."""
    return wire.build_plaintext(refusal_meta(code, **fields), b"")


def answer_plaintexts(result: Mapping[str, Any], *, room: int) -> list[bytes]:
    """The plaintexts of a success answer: chunk 0 meta ``{"status":"ok"}``, later ``{}``; ``room`` is the plaintext
    budget of one chunk. Raises :class:`Refusal` ``frame.too_large`` above :data:`MAX_ANSWER` or when the chunk
    envelopes would exceed :data:`RELAY_DEVICE_RESPONSE_BYTES` (never deliverable): refused before anything is
    stored."""
    try:
        data = canon.dumps(dict(result))
    except canon.JcsError:
        raise Refusal("internal") from None
    if len(data) > MAX_ANSWER:
        raise Refusal("frame.too_large")
    out: list[bytes] = []
    first = wire.build_plaintext({"status": "ok"}, b"")
    later = wire.build_plaintext({}, b"")
    pos = 0
    while True:
        head = first if not out else later
        take = room - len(head)
        out.append(head + data[pos : pos + take])
        pos += take
        if pos >= len(data):
            if sum(len(p) + wire.OVERHEAD for p in out) > RELAY_DEVICE_RESPONSE_BYTES:
                raise Refusal("frame.too_large")
            return out
