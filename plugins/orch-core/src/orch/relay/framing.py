MAX_ANSWER = 4 << 20  # plaintext of one answer; above it: frame.too_large
SCOPE_ORDER = ("look", "decide", "operate", "type")
META_KEYS = frozenset({"op", "args", "idem", "rd"})
#: O1 (orch-52 final, 15 Oct 2026): ``outcome.get`` answers ``pending`` for an idem (= event id) that has no outcome
#: record yet until the event id's ULID time + 900 s + 300 s; only after that is "no record" definite.
PENDING_NO_RECORD_MS = 900_000 + 300_000
#: O3 (orch-52 final): an event id's ULID time must lie in [host now - 900 s, host now + 300 s], else event.expired
FRESH_PAST_MS, FRESH_FUTURE_MS = 900_000, 300_000

IDEM_RE = re.compile(r"[0-7][0-9A-HJKMNP-TV-Z]{25}")  # = the event id (orch-52 final)
_CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"


def ulid_ms(ulid: str) -> int:
    """The millisecond time of a ULID (its first 10 characters, Crockford base32)."""
    n = 0
    for c in ulid[:10]:
        n = n * 32 + _CROCKFORD.index(c)
    return n


_RD = re.compile(r"sha256:[0-9a-f]{64}")
#: the host's GRANT_SHAPE (orch.host.auth, §0.5); a test keeps the two equal (orch.host is import-banned here)
GRANT_SHAPE = re.compile(r"gr_[0-7][0-9A-HJKMNP-TV-Z]{25}\.[A-Za-z0-9_-]{43}")


@dataclass(frozen=True)
class OpSpec:
    backend: str  # the backend op (RELAY_OPS)
    kind: str  # "read" | "write"
    scope: str  # the scope the device needs in BOTH its certificate and the member list
    event: str | None = None  # a write's one event type (the closed event/scope table)


#: The ONE closed table (11A.4): relay request op -> backend op. Reads are the host reads served synchronously on the
#: worker thread (filtered for the viewer exactly as P); writes are device-signed events through relay.submit.
OPS: Mapping[str, OpSpec] = {
    "ticket.query": OpSpec("ticket.query", "read", "look"),
    "ticket.get": OpSpec("ticket.get", "read", "look"),
    "ticket.text": OpSpec("ticket.text", "read", "look"),
    "needs": OpSpec("needs", "read", "look"),
    "activity.list": OpSpec("activity.list", "read", "look"),
    "workspace.show": OpSpec("workspace.show", "read", "look"),
    "workspace.settings": OpSpec("workspace.settings", "read", "look"),
    "member.list": OpSpec("member.list", "read", "look"),
    "whoami": OpSpec("whoami", "read", "look"),
    "outcome.get": OpSpec("outcome.get", "read", "look"),
    "new_ticket": OpSpec("relay.submit", "write", "operate", "ticket.created"),
    "answer": OpSpec("relay.submit", "write", "decide", "question.answered"),
}

#: The ONE closed retry classification (orch-52's final #465 decisions, 15 Oct 2026): every answer code a device can
#: get maps to one class; the R2 tests and the phone use this table as data. An UNKNOWN code is ``D`` (fail closed).
#: A: resend the same bytes and idem (same rid within 240 s, else a new rid with the same idem = event id).
#: B: unknown: settle by reading the log (``outcome.get`` with the idem, or the ticket).
#: C-auto: the phone rebuilds the event (a new event id) without a new review (``next_key``, a fresh member list).
#: C-review: the person must review again before anything is re-signed.
#: D: definite: the answer is the outcome (``committed`` and ``duplicate: true`` included).
RETRY: Mapping[str, str] = {
    **dict.fromkeys(
        (
            "stale_epoch", "stale_sequence", "stale_timestamp", "relay.stale_epoch_hint", "relay.silence",
            "relay.timeout", "cancelled", "store.busy", "lock.busy", "rate.limited", "quota.host", "host.restarting",
            "conn.overloaded", "outcome.unknown",
        ),
        "A",
    ),
    **dict.fromkeys(("already_done", "rid_conflict", "pending", "idem.expired"), "B"),
    **dict.fromkeys(("members.stale", "ticket.key_not_next"), "C-auto"),
    **dict.fromkeys(
        ("event.bad_base", "question.stale", "event.expired", "event.abandoned", "outcome.unknown_idem"), "C-review"
    ),
    **dict.fromkeys(
        (
            "committed", "event.duplicate_id", "ticket.exists", "idem.conflict", "idem.invalid", "idem.required",
            "forbidden_scope", "not_member", "revoked", "bad_signature", "malformed", "busy", "req.invalid",
            "grant.secret_in_args", "op.not_allowed", "invalid.input", "frame.too_large", "not_found", "internal",
        ),
        "D",
    ),
}  # fmt: skip
#: ``outcome.unknown_idem`` is B ("unknown_idem before the bound") while ``outcome.get`` would still answer
#: ``pending`` (:data:`PENDING_NO_RECORD_MS` after the event id's ULID time); the bridge answers ``pending`` then, so a
#: device that sees the code itself is past the bound: "lost past the bound", C-review.


def retry_class(code: str) -> str:
    """The class of ``code``; an unknown code is ``D`` (fail closed)."""
    return RETRY.get(code, "D")


class Refusal(Exception):  # noqa: N818 - a sealed refusal, not an error of this process
    """A sealed refusal: ``code`` and its documented fields. The message never carries request data."""

    def __init__(self, code: str, **fields: Any) -> None:
        super().__init__(code)
        self.code, self.fields = code, fields


@dataclass(frozen=True)
class Identity:
    """The verified identity of a request (proto §8.6 steps 1 to 4), relay side; the host adapter turns it into
    ``orch.host.relayid.RelayIdentity``. ``device_id``/``person_id`` are ``d_``/``p_`` prefixed."""

    workspace_id: str
    device_id: str
    person_id: str
    cert_digest: str
    epoch: int
    list_hash: str
    rd: str | None = None

    @property
    def principal(self) -> str:
        return f"r:{self.device_id}"


def grant_shaped(obj: Any) -> bool:
    """A grant-shaped string anywhere in ``obj`` (keys included)."""
    stack = [obj]
    while stack:
        x = stack.pop()
        if type(x) is str:
            if GRANT_SHAPE.search(x):
                return True
        elif type(x) is list:
            stack.extend(x)
        elif type(x) is dict:
            stack.extend(x.keys())
            stack.extend(x.values())
    return False


@dataclass(frozen=True)
class Request:
    op: str
    spec: OpSpec
    args: dict[str, Any]
    idem: str | None
    rd: str | None


def check_meta(meta: Mapping[str, Any], data: bytes) -> Request:
    """Step 11's first checks, in order, before any column is resolved: ``auth`` -> ``req.invalid``; a grant-shaped
    string -> ``grant.secret_in_args``; other unknown keys, non-object args or non-empty data -> ``req.invalid``; an op
    outside :data:`OPS` -> ``forbidden_scope``; the idem rules (``idem.required`` / ``req.invalid``)."""
    if "auth" in meta:
        raise Refusal("req.invalid")
    if grant_shaped(meta):
        raise Refusal("grant.secret_in_args")
    if set(meta) - META_KEYS or "args" not in meta or type(meta["args"]) is not dict or data:
        raise Refusal("req.invalid")
    spec = OPS.get(meta["op"])
    if spec is None:
        raise Refusal("forbidden_scope")
    idem = meta.get("idem")
    if spec.kind == "write":
        if idem is None:
            raise Refusal("idem.required")
        if type(idem) is not str or not IDEM_RE.fullmatch(idem):
            raise Refusal("idem.invalid")
    elif "idem" in meta:
        raise Refusal("req.invalid")
    rd = meta.get("rd")
    if "rd" in meta and (type(rd) is not str or not _RD.fullmatch(rd)):
        raise Refusal("req.invalid")
    return Request(meta["op"], spec, dict(meta["args"]), idem, rd)


def refusal_plaintext(code: str, **fields: Any) -> bytes:
    return wire.build_plaintext({"refusal": code, **fields}, b"")


def answer_plaintexts(result: Mapping[str, Any], *, room: int) -> list[bytes]:
    """The plaintexts of a success answer: chunk 0 meta ``{"status":"ok"}``, later ``{}``; ``room`` is the plaintext
    budget of one chunk. Raises :class:`Refusal` ``frame.too_large`` above :data:`MAX_ANSWER`."""
    try:
        data = canon.dumps(dict(result))
    except canon.JcsError:
        raise Refusal("internal", retryable=False) from None
    if len(data) > MAX_ANSWER:
        raise Refusal("frame.too_large", retryable=False)
    out: list[bytes] = []
    first = wire.build_plaintext({"status": "ok"}, b"")
    later = wire.build_plaintext({}, b"")
    pos = 0
    while True:
        head = first if not out else later
        take = room - len(head)
        out.append(head + data[pos : pos + take])
        pos += take
        if pos >= len(data):
            return out
