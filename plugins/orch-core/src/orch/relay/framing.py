"""R2 framing (contract 11A.4, 11A.5 "R2 framing"): what a column-R bridge request carries inside the seal, what the
host answers, and the closed tables. Pure: no I/O, no keys, no clock. orch-mobile codes against this module's tables
and the vectors ``tests/relay/r2_vectors/r2_framing.json`` (generated by ``scripts/gen_r2_framing_vectors.py``).

**Request meta** (strict JSON, proto §2.3; at most 64 KiB; ``data`` MUST be empty)::

    {"op": <a key of OPS>, "args": {...}, "idem": "<event id ULID>"?, "rd": "sha256:<hex>"?}

* ``op``: the relay request op. One closed table, :data:`OPS`, maps it to a backend op; an op outside it is a sealed
  ``forbidden_scope``. ``args`` is the backend op's args object.
* ``idem`` (§0.7): **mandatory on every write** (else ``idem.required``) and **absent on every read** (else
  ``req.invalid``). For a write it is the event id (orch-52 final, 15 Oct 2026): a ULID (else ``idem.invalid``) equal
  to ``args.events[0].id`` (else ``invalid.input``, 14.6 P1); the outcome key is ``(ws, r:<device>, event id)``.
* ``rd`` (H12d): carried into the identity. **H12d-3:** while the workspace's ``required_reader`` is at least 1 the
  host serves a request only when ``rd`` names the device's current reader record and that record's level is at
  least the required one (orch-v2-host §0.8.6 item 9.5); otherwise ``sign.convenience_readers`` with ``reason``
  ``no_declaration`` (no ``rd``), ``declaration_unknown`` (not the current record: re-declare with
  ``reader.declare`` and resend) or ``reader_too_old`` (with ``required`` and ``declared``). ``reader.declare`` is
  exempt: it is how a device gets an ``rd``.
* Any other key is ``req.invalid``; in particular an ``auth`` key (column R carries no grant). A grant-shaped string
  anywhere in the meta is ``grant.secret_in_args``. Both are checked before any column is resolved.

**Writes** (``kind`` ``write``) are ``relay.submit``: ``args`` is ``{"log": <ticket uid>, "events": [<event>]}`` with
exactly one F1 person event, signed by the requesting device's ``dk_sig`` over ``person_signing_bytes(ws, log, E)``
(F1 §5.3; ``seq``, ``at``, ``prev``, ``ws_seq``, ``host_sig`` absent). The event type must be the one :data:`OPS`
names for the op (the closed event/scope table of ``relay/submit.py``).

**Answer** (response chunks, each ≤ 256 KiB; the whole answer's chunk envelopes ≤ :data:`RELAY_DEVICE_RESPONSE_BYTES`,
the relay's per-device budget of undelivered response bytes, so ``cj(result)`` ≤ :data:`MAX_ANSWER`):

* success: chunk 0 meta exactly ``{"status": "ok"}``, later chunks meta exactly ``{}``; ``data`` across the chunks is
  ``cj(result)`` (the §0.3 Result object); the last chunk has ``LAST``. Above the cap: ``frame.too_large`` (nothing
  stored but that refusal).
* refusal: one chunk, ``LAST | REFUSAL``, meta ``{"refusal": <code>, ...}`` with EXACTLY the fields of
  :func:`refusal_meta` (the closed field sets): a proto §14 code with its documented field (``high``, ``host_ms``,
  ``epoch``, ``status``) and nothing else; a host §0.6 code with ``retryable`` (DERIVED from :data:`RETRY`, never
  passed in), ``seqs`` only for a write whose events partly landed (never "not run"), ``next_key`` only for
  ``ticket.key_not_next``, and (H12d-3) ``reason`` only for the codes of :data:`REASONS` (a member of the code's
  closed set) with ``required`` and ``declared`` only for ``sign.convenience_readers`` ``reader_too_old``. A
  refusal never echoes request text.

:data:`RETRY` is the one closed retry classification shared by the R2 tests, the doc and the phone;
:data:`RETRY_CONTEXT` holds its two context rules (orch-52 ruling C).
"""

