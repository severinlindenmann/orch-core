def manifest(addon: str, version: str = "1.0.0", caps: list[str] | None = None, **extra: Any) -> str:
    m: dict[str, Any] = {
        "schema": "orch.addon/3",
        "name": addon,
        "version": version,
        "title": addon.title(),
        "entry": {"cmd": ["python3", "{pkg}/main.py"]},
        "api": ">=1.0,<2",
        "min_core": "2.0.0",
        "capabilities": sorted(caps or []),
    }
    m.update(extra)
    return json.dumps(m, sort_keys=True)


def files_for(
    addon: str, version: str = "1.0.0", caps: list[str] | None = None, extra: dict[str, str] | None = None, **mx: Any
) -> dict[str, str]:
    return {"orch-addon.json": manifest(addon, version, caps, **mx), "main.py": "print('hello')\n", **(extra or {})}


def entry(
    addon: str,
    files: dict[str, str],
    version: str = "1.0.0",
    caps: list[str] | None = None,
    signer: str | None = None,
    market: str = OTHER,
    **kw: Any,
) -> dict[str, Any]:
    e: dict[str, Any] = {
        "id": addon,
        "version": version,
        "source": {"git": "https://github.com/acme/" + addon, "subdir": "pkg"},
        "commit": COMMIT,
        "package_sha256": package_digest({p: t.encode() for p, t in files.items()}),
        "capabilities": sorted(caps or []),
        "min_orch": "2.0.0",
    }
    e.update(kw)
    if signer:
        e["publisher"] = {"key": PUB[signer], "sig": ""}
        e["publisher"]["sig"] = sign_entry(e, KEYS[signer], market)
    return e


def index(repo: str, entries: list[dict[str, Any]], version: int = 7, name: str = "acme-market") -> dict[str, Any]:
    return {"format": "orch.market/1", "name": name, "version": version, "source": {"git": repo}, "addons": entries}


def ctx(**kw: Any) -> dict[str, Any]:
    c: dict[str, Any] = {
        "actor": "human",
        "core_version": "2.0.1",
        "market_repo": OTHER,
        "isolation": True,
        "official": {"repo": OFFICIAL, "key": PUB["official"]},
        "hub": None,
        "git_hosts": ["github.com", "gitlab.com"],
        "seen": {},
        "builtin": ["wiki", "terminals", "dashboard"],
        "official_ids": ["github", "landing"],
        "moved": [],
        "installed": {},
        "known_keys": {},
        "last_version": None,
    }
    c.update(kw)
    return c


CASES: list[dict[str, Any]] = []


def add(name: str, check: str, args: dict[str, Any], expect: dict[str, Any]) -> None:
    CASES.append({"name": name, "check": check, "args": copy.deepcopy(args), "expect": expect})


def ok(**kw: Any) -> dict[str, Any]:
    return {"ok": kw}


def refuse(code: str) -> dict[str, Any]:
    return {"refuse": "market." + code}


