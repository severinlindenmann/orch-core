def _git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), "-c", "user.name=t", "-c", "user.email=t@t", *args],
                          capture_output=True, text=True)


needs_git = pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")
needs_sh = pytest.mark.skipif(shutil.which("sh") is None, reason="sh not installed")


def _hooks_dir(repo):
    out = _git(repo, "rev-parse", "--git-path", "hooks").stdout.strip()
    return (repo / out).resolve()


def _new_repo(ws_root, name):
    repo = ws_root / name
    repo.mkdir()
    assert _git(repo, "init", "-q").returncode == 0
    return repo


def _rows(ws, **kw):
    return {p.name: a for p, a in install_hooks(ws, **kw)}


