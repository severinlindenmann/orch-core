@needs_git
@needs_sh
def test_install_hooks_skips_then_chains_existing_commit_msg(configure, ws_root):
    repo = _new_repo(ws_root, "hub")
    hooks = _hooks_dir(repo)
    hooks.mkdir(parents=True, exist_ok=True)
    marker = ws_root / "old-hook-ran"
    old = f"#!/bin/sh\necho \"$1\" > {shlex.quote(str(marker))}\n"
    (hooks / "commit-msg").write_text(old, encoding="utf-8")
    (hooks / "commit-msg").chmod(0o755)
    ws = configure(git={"repos": {"hub": {}}})
    got = _rows(ws)["hub"]
    assert got.startswith("skipped: a commit-msg hook already exists") and "--force" in got
    assert (hooks / "commit-msg").read_text(encoding="utf-8") == old
    got = _rows(ws, force=True)["hub"]
    assert got.startswith("installed") and "commit-msg.pre-orch" in got
    assert (hooks / "commit-msg.pre-orch").read_text(encoding="utf-8") == old
    assert "hook commit-msg" in (hooks / "commit-msg").read_text(encoding="utf-8")
    assert _rows(ws, force=True)["hub"] == "unchanged"
    # the chained hook runs after the orch check passes (orch is faked to accept everything)
    fake_bin = ws_root / "bin"
    fake_bin.mkdir()
    (fake_bin / "orch").write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
    (fake_bin / "orch").chmod(0o755)
    msg = ws_root / "MSG"
    msg.write_text("x\n", encoding="utf-8")
    r = subprocess.run(["sh", str(hooks / "commit-msg"), str(msg)], capture_output=True, text=True,
                       env={"PATH": f"{fake_bin}:/usr/bin:/bin"})
    assert r.returncode == 0, r.stderr
    assert marker.read_text(encoding="utf-8").strip() == str(msg)
    # and does not run when orch rejects the message
    marker.unlink()
    (fake_bin / "orch").write_text("#!/bin/sh\nexit 1\n", encoding="utf-8")
    r = subprocess.run(["sh", str(hooks / "commit-msg"), str(msg)], capture_output=True, text=True,
                       env={"PATH": f"{fake_bin}:/usr/bin:/bin"})
    assert r.returncode == 1 and not marker.exists()


def _common_hooks(repo):
    out = _git(repo, "rev-parse", "--git-common-dir").stdout.strip()
    return (repo / out).resolve() / "hooks"


def _fake_orch(ws_root, exit_code):
    fake_bin = ws_root / "bin"
    fake_bin.mkdir(exist_ok=True)
    (fake_bin / "orch").write_text(f"#!/bin/sh\necho \"$@\" >> {shlex.quote(str(ws_root / 'orch-calls'))}\nexit {exit_code}\n",
                                   encoding="utf-8")
    (fake_bin / "orch").chmod(0o755)
    return {"PATH": f"{fake_bin}:/usr/bin:/bin"}


@needs_git
def test_hooks_path_without_commit_msg_gets_one_that_runs_the_local_check(configure, ws_root):
    """#18: a repo with its own core.hooksPath gets a tracked commit-msg there that runs this clone's orch hook."""
    repo = _new_repo(ws_root, "hub")
    _git(repo, "config", "core.hooksPath", "scripts/git-hooks")
    (repo / "scripts" / "git-hooks").mkdir(parents=True)
    (repo / "scripts" / "git-hooks" / "pre-commit").write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
    ws = configure(git={"repos": {"hub": {}}})
    got = _rows(ws)["hub"]
    tracked = repo / "scripts" / "git-hooks" / "commit-msg"
    assert got.startswith("installed") and "scripts/git-hooks/commit-msg" in got and "commit" in got.split(";", 1)[1]
    text = tracked.read_text(encoding="utf-8")
    assert text.startswith("#!/bin/sh\n") and "# >>> orch commit-msg check >>>" in text
    assert str(ws_root) not in text and "ORCH_HOME" not in text  # nothing machine-specific in a tracked file
    assert tracked.stat().st_mode & 0o111
    assert is_orch_hook((_common_hooks(repo) / "commit-msg").read_text(encoding="utf-8"))  # the local, untracked hook
    assert _git(repo, "config", "--get", "core.hooksPath").stdout.strip() == "scripts/git-hooks"  # untouched
    assert hook_state(repo) == "installed"


@needs_git
@needs_sh
def test_hooks_path_commit_msg_gets_the_call_once(configure, ws_root):
    repo = _new_repo(ws_root, "hub")
    custom = repo / "custom hooks"  # inside the worktree, configured by absolute path
    custom.mkdir()
    marker = ws_root / "theirs-ran"
    theirs = f"#!/usr/bin/env bash\n# their own check\necho \"$1\" > {shlex.quote(str(marker))}\nexit 0\n"
    (custom / "commit-msg").write_text(theirs, encoding="utf-8")
    (custom / "commit-msg").chmod(0o755)
    _git(repo, "config", "core.hooksPath", str(custom))
    ws = configure(git={"repos": {"hub": {}}})
    got = _rows(ws)["hub"]
    assert got.startswith("installed") and "added" in got and "commit" in got
    text = (custom / "commit-msg").read_text(encoding="utf-8")
    assert text.startswith("#!/usr/bin/env bash\n# >>> orch commit-msg check >>>")  # runs before their exit 0
    assert text.endswith(theirs.split("\n", 1)[1])  # their script is kept as it was
    again = _rows(ws)["hub"]
    assert again.startswith("unchanged") and "commit" in again  # idempotent, and still says where the file is
    assert (custom / "commit-msg").read_text(encoding="utf-8") == text
    assert text.count("# >>> orch commit-msg check >>>") == 1
    assert (custom / "commit-msg").stat().st_mode & 0o777 == 0o755  # permissions kept
    assert not (custom / "commit-msg.pre-orch").exists()
    # a commit runs the orch check first, then their hook; a rejected message stops it
    env = _fake_orch(ws_root, 0)
    msg = ws_root / "MSG"
    msg.write_text("x\n", encoding="utf-8")
    r = subprocess.run(["sh", str(custom / "commit-msg"), str(msg)], capture_output=True, text=True, cwd=repo, env=env)
    assert r.returncode == 0, r.stderr
    assert "hook commit-msg" in (ws_root / "orch-calls").read_text(encoding="utf-8") and marker.exists()
    marker.unlink()
    env = _fake_orch(ws_root, 1)
    r = subprocess.run(["sh", str(custom / "commit-msg"), str(msg)], capture_output=True, text=True, cwd=repo, env=env)
    assert r.returncode == 1 and not marker.exists()


